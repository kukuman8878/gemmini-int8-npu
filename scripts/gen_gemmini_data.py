#!/usr/bin/env python3
# gen_gemmini_data.py : 生成 Gemmini 一致性测试的 C 头文件 (W14)
#   读 conversion.py 生成的 int8 对齐数据 + golden, 输出 C 数组头文件
#   用法: python3 scripts/gen_gemmini_data.py [OUTDIR]
import os
import numpy as np

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "benchmarks", "phone_layer_01")
OUT = os.environ.get("OUTDIR", "/tmp/opencode/gemmini_data")
os.makedirs(OUT, exist_ok=True)

A = np.load(os.path.join(HERE, "a_int8.npy"))       # [M,K] int8
B = np.load(os.path.join(HERE, "b_int8.npy"))       # [K,N] int8
bias = np.load(os.path.join(HERE, "bias_int32.npy"))# [N] int32
golden = np.load(os.path.join(HERE, "golden_tiles.npy"))  # [Mt,Nt,4,4] int32

M, K = A.shape
_, N = B.shape

# N 子集 (Gemmini 验证一个真实层 tile 即可; 默认 16 列, 可 N_SUB 环境变量覆盖)
N_SUB = int(os.environ.get("N_SUB", "16"))
N_SUB = min(N_SUB, N)
B = B[:, :N_SUB]
bias = bias[:N_SUB]
N = N_SUB
golden = golden[:, :(N_SUB // 4), :, :]

def dump_i8(name, arr, fh):
    fh.write(f"static const int8_t {name}[{arr.size}] = {{\n")
    flat = arr.flatten()
    for i in range(0, len(flat), 32):
        fh.write("  " + ",".join(str(int(x)) for x in flat[i:i+32]) + ",\n")
    fh.write("};\n\n")

def dump_i32(name, arr, fh):
    fh.write(f"static const int32_t {name}[{arr.size}] = {{\n")
    flat = arr.flatten()
    for i in range(0, len(flat), 16):
        fh.write("  " + ",".join(str(int(x)) for x in flat[i:i+16]) + ",\n")
    fh.write("};\n\n")

with open(os.path.join(OUT, "phone_layer_data.h"), "w") as fh:
    fh.write("// auto-generated by scripts/gen_gemmini_data.py\n")
    fh.write("#include <stdint.h>\n\n")
    fh.write(f"#define PHONE_M {M}\n#define PHONE_K {K}\n#define PHONE_N {N}\n\n")
    dump_i8("phone_A", A, fh)
    dump_i8("phone_B", B, fh)
    dump_i32("phone_bias", bias, fh)
    # golden 展平成 [M,N] (golden_tiles 是 pad 后的 [Mt,Nt,4,4], 取 [0:M,0:N])
    Mt, Nt, _, _ = golden.shape
    g2d = golden.transpose(0, 2, 1, 3).reshape(Mt * 4, Nt * 4)[:M, :N]
    dump_i32("phone_golden", g2d, fh)

print(f"生成 {os.path.join(OUT, 'phone_layer_data.h')}")
print(f"  A[{M},{K}] B[{K},{N}] bias[{N}] golden[{M},{N}]")
print(f"  头文件大小: {os.path.getsize(os.path.join(OUT, 'phone_layer_data.h'))/1024:.0f} KB")
